import { expect } from '@playwright/test'
import { test, completed, count, createVersion, derive, editorPath, fixtureCanvas, manualRun, publishVersion, read, rename, saved, send, type Draft } from '../studio-builder-support'

test('P8-E2E-04/05/06/07/26: version lineage, independent revision zero canvases, readonly, concurrent numbering and archive',async({page,context})=>{
  const {token,created}=await fixtureCanvas(page,'P8 versions')
  const initial=await saved(page,token,created)
  const v1=await createVersion(page,created)
  expect(v1.sourceDraftId).toBe(created.createdDraftId)
  expect(v1.sourceRevision).toBe(initial.revision)
  await publishVersion(page,token,created,v1.id)
  await page.goto(editorPath(created))
  await page.getByRole('button',{name:'AI 创作',exact:true}).click()
  await send(page,'P8FIX: label=VersionTwo')
  await completed(page)
  const second=await saved(page,token,created)
  const v2=await createVersion(page,created)
  expect(v2.versionNumber).toBe(v1.versionNumber+1)
  const a=await derive(page,created,v1.id,'From V1')
  const b=await derive(page,created,v2.id,'From V2')
  const first=await read<Draft>(page,token,`/workflows/${a.id}/drafts/${a.createdDraftId}`)
  expect(first.definition).toEqual(initial.definition)
  const other=await read<Draft>(page,token,`/workflows/${b.id}/drafts/${b.createdDraftId}`)
  expect(other.definition).toEqual(second.definition)
  await page.goto(editorPath(a))
  const execution=await manualRun(page,token,a)
  expect(execution.source).toMatchObject({kind:'draft_revision',draftId:a.createdDraftId,revision:0})
  expect(execution.workflowVersionId).toBeNull()
  const pageB=await context.newPage()
  await pageB.goto(editorPath(b))
  await page.getByRole('button',{name:'AI 创作',exact:true}).click()
  await send(page,'P8FIX: label=DraftA')
  await completed(page)
  await saved(page,token,a)
  await expect(pageB.getByTestId('studio-node-p8-decision')).toContainText('VersionTwo')
  expect((await read<Draft>(page,token,`/workflows/${b.id}/drafts/${b.createdDraftId}`)).definition).toEqual(second.definition)
  const [va,vb]=await Promise.all([createVersion(page,a),createVersion(pageB,b)])
  expect(new Set([v1.versionNumber,v2.versionNumber,va.versionNumber,vb.versionNumber]).size).toBe(4)
  expect(va.sourceDraftId).toBe(a.createdDraftId)
  expect(vb.sourceDraftId).toBe(b.createdDraftId)
  expect(vb.sourceRevision).toBe(0)
  expect((await read<Array<{status:string;workflowVersionId:string}>>(page,token,`/workflows/${created.id}/deployments`)).find(item=>item.status==='active')?.workflowVersionId).toBe(v1.id)
  const replay=await page.request.post(`/api/v1/workflows/${b.id}/versions`,{headers:{Authorization:`Bearer ${token}`},data:{draftId:b.createdDraftId,draftRevision:0}})
  expect(replay.ok(),await replay.text()).toBeTruthy()
  expect((await replay.json()).id).toBe(vb.id)
  await page.goto(`/workflows/${created.id}/versions/${v1.id}/editor`)
  for(const label of ['保存','版本','发布','AI 创作','撤销','重做']) await expect(page.locator('header').getByRole('button',{name:label,exact:true})).toBeDisabled()
  await page.getByTestId('studio-node-p8-decision').click()
  await page.keyboard.press('Delete')
  await page.keyboard.press('Meta+z')
  await page.keyboard.press('Meta+v')
  await expect(page.getByTestId('studio-node-p8-decision')).toContainText('Initial')
  await page.reload()
  await expect(page.getByTestId('studio-node-p8-decision')).toContainText('Initial')
  const versionStarted=page.waitForResponse(response=>response.url().endsWith(`/workflow-versions/${v1.id}/executions`)&&response.request().method()==='POST')
  await page.locator('header').getByRole('button',{name:'运行',exact:true}).click()
  const accepted=await versionStarted
  expect(accepted.status(),await accepted.text()).toBe(202)
  const versionExecution=(await accepted.json()).executionId as string
  await expect.poll(async()=>(await read<{status:string}>(page,token,`/executions/${versionExecution}`)).status,{timeout:120_000}).toBe('succeeded')
  expect((await read<{source:unknown}>(page,token,`/executions/${versionExecution}`)).source).toEqual({kind:'version',versionId:v1.id,versionNumber:v1.versionNumber})
  await page.goto(`/workflows/${created.id}`)
  const row=page.getByText('From V1',{exact:true}).locator('..').locator('..')
  await row.getByRole('button',{name:'归档草稿',exact:true}).click()
  await expect(row.getByRole('button',{name:'恢复草稿',exact:true})).toBeVisible()
  await page.goto(editorPath(a))
  await expect(page.getByRole('button',{name:'AI 创作',exact:true})).toBeDisabled()
  await page.goto(`/workflows/${created.id}`)
  await page.getByText('From V1',{exact:true}).locator('..').locator('..').getByRole('button',{name:'恢复草稿',exact:true}).click()
  await page.goto(editorPath(a))
  await expect(page.getByTestId('studio-node-p8-decision')).toContainText('DraftA')
  await pageB.close()
})

test('P8-E2E-08/10: saving an older snapshot keeps later manual edits; same draft conflict is resolved by UI',async({page,context})=>{
  const {token,created}=await fixtureCanvas(page,'P8 save race')
  const path=`**/workflows/${created.id}/drafts/${created.createdDraftId}`
  let release!:()=>void
  let held!:()=>void
  const pending=new Promise<void>(resolve=>{held=resolve})
  const gate=new Promise<void>(resolve=>{release=resolve})
  let intercepted=false
  await page.route(path,async route=>{
    if(route.request().method()!=='PUT'||intercepted){await route.continue();return}
    intercepted=true
    const response=await route.fetch()
    held()
    await gate
    await route.fulfill({response})
  })
  await rename(page,'Submitted')
  await pending
  await rename(page,'LaterHumanEdit')
  release()
  await expect(page.getByTestId('studio-node-p8-decision')).toContainText('LaterHumanEdit')
  await saved(page,token,created)
  await page.unroute(path)
  await page.reload()
  await expect(page.getByTestId('studio-node-p8-decision')).toContainText('LaterHumanEdit')
  const other=await context.newPage()
  await other.goto(editorPath(created))
  await expect(other.getByTestId('studio-node-p8-decision')).toBeVisible()
  await rename(page,'WindowOne')
  await saved(page,token,created)
  await rename(other,'WindowTwo')
  const conflict=other.getByRole('dialog',{name:'草稿版本冲突'})
  await expect(conflict).toBeVisible()
  await conflict.getByRole('button',{name:'载入服务器版本',exact:true}).click()
  await expect(other.getByTestId('studio-node-p8-decision')).toContainText('WindowOne')
  expect(await count(page,token,created.id)).toBe(0)
  await other.close()
})

test('P8-E2E-09: a command prepared before a human edit is stale, re-read and replaced without overwriting',async({page})=>{
  const {token,created}=await fixtureCanvas(page,'P8 stale')
  let session=''
  page.on('request',request=>{const match=request.url().match(/\/studio-builder\/sessions\/([^/]+)\/runs$/);if(match)session=match[1]!})
  await page.route('**/studio-builder/sessions/*/events?*',route=>route.abort('connectionreset'))
  await page.reload()
  await page.getByRole('button',{name:'AI 创作',exact:true}).click()
  const run=await send(page,'P8FIX: label=AIUpdated')
  await expect.poll(async()=>{
    const entries=await read<{items:Array<{runId:string;payload:{type:string;command?:unknown}}> }>(page,token,`/studio-builder/sessions/${session}/entries`)
    return entries.items.some(entry=>entry.runId===run&&entry.payload.type==='command')
  },{timeout:60_000}).toBeTruthy()
  await rename(page,'HumanChanged')
  await saved(page,token,created)
  await page.unroute('**/studio-builder/sessions/*/events?*')
  await completed(page)
  const entries=await read<{items:Array<{payload:{type:string;status?:string}}> }>(page,token,`/studio-builder/sessions/${session}/entries`)
  expect(entries.items.some(entry=>entry.payload.type==='command_acknowledged'&&entry.payload.status==='stale')).toBeTruthy()
  expect(await count(page,token,created.id)).toBe(0)
})
