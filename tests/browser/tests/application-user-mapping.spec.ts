import { expect, test } from '@playwright/test'

test('deployment advanced user mapping saves and prefills while Memory has one read/write connection', async ({ page }) => {
  const applicationId = process.env.AGENTX_USER_MAPPING_APP
  const version = process.env.AGENTX_USER_MAPPING_VERSION
  const environment = process.env.AGENTX_USER_MAPPING_ENVIRONMENT
  if (!applicationId || !version || !environment) throw new Error('Application user mapping fixture is required')
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码').fill('agentx-e2e-admin-password')
  await page.getByRole('button', { name: '登录' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto(`/applications/${applicationId}`)
  await page.getByRole('button', { name: '创建部署' }).click()
  let dialog = page.getByRole('dialog', { name: '部署', exact: true })
  await expect(dialog.locator('details')).not.toHaveAttribute('open', '')
  await dialog.getByLabel('工作流版本').click()
  await page.getByRole('option', { name: version, exact: true }).click()
  await dialog.getByLabel('环境', { exact: true }).click()
  await page.getByRole('option', { name: environment, exact: true }).click()
  await dialog.getByText('高级配置', { exact: true }).click()
  await expect(dialog.getByText(/不验证用户身份/)).toBeVisible()
  await expect(dialog.getByText(/不决定工作流、工具或凭证权限/)).toBeVisible()
  await dialog.getByRole('combobox', { name: 'API 用户标识参数' }).click()
  await expect(page.getByRole('option', { name: '不设置', exact: true })).toBeVisible()
  await page.getByRole('option', { name: 'customerId', exact: true }).click()
  const saved = page.waitForResponse(response => response.url().endsWith(`/applications/${applicationId}/deployments`) && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  const response = await saved
  expect(response.status()).toBe(202)
  expect(await response.json()).toMatchObject({ apiUserIdInput: 'customerId' })
  await expect(dialog).toBeHidden()
  const latestDeployment = page.getByRole('group', { name: `${environment} · ${version}`, exact: true }).first()
  await expect(latestDeployment.getByText('API 用户标识参数: customerId')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('application-user-mapping.png'), fullPage: true })
  await page.getByRole('button', { name: '创建部署' }).click()
  dialog = page.getByRole('dialog', { name: '部署', exact: true })
  await dialog.getByLabel('工作流版本').click()
  await page.getByRole('option', { name: version, exact: true }).click()
  await dialog.getByText('高级配置', { exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: 'API 用户标识参数' })).toHaveText('customerId')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('tab', { name: '调用记录', exact: true }).click()
  await page.getByPlaceholder('按用户 ID 筛选').fill(process.env.AGENTX_USER_MAPPING_USER ?? '')
  await expect(page.getByText(process.env.AGENTX_USER_MAPPING_USER ?? '', { exact: true }).first()).toBeVisible()
  await page.goto('/memory')
  await page.getByRole('button', { name: '接入记忆服务' }).click()
  const memory = page.getByRole('dialog', { name: '接入记忆服务' })
  await expect(memory.getByLabel('连接名称')).toBeVisible()
  for (const label of ['资源名称', '记忆命名空间', '访问模式']) await expect(memory.getByText(label, { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '添加记忆命名空间' })).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('memory-connection.png'), fullPage: true })
  await memory.getByLabel('连接名称').fill(`UI Mem0 ${process.env.AGENTX_E2E_RUN_ID}`)
  await memory.getByLabel('Endpoint').fill('https://mem0.example.test')
  await memory.getByRole('combobox', { name: '所属部门' }).click()
  await page.getByRole('option').first().click()
  const created = page.waitForResponse(response => response.url().endsWith('/memory/connections') && response.request().method() === 'POST')
  await memory.getByRole('button', { name: '保存', exact: true }).click()
  const connection = await (await created).json()
  await expect(memory).toBeHidden()
  await page.goto(`/memory/${connection.id}`)
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑', exact: true })
  await edit.getByRole('combobox', { name: '状态' }).click()
  await page.getByRole('option', { name: '停用', exact: true }).click()
  const updated = page.waitForResponse(response => response.url().endsWith(`/memory/connections/${connection.id}`) && response.request().method() === 'PATCH')
  await edit.getByRole('button', { name: '保存', exact: true }).click()
  expect(await (await updated).json()).toMatchObject({ status: 'disabled' })
  await expect(edit).toBeHidden()
})
