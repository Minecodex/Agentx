import {expect,test} from '@playwright/test'
import {createHash} from 'node:crypto'
import {writeFileSync} from 'node:fs'
import {login,read} from '../studio-builder-support'
import {clickForResponse,trackAccessToken} from '../browser-http'
import {executeCase,verifyHistoricalPage,type Scenario} from '../plan9-page-support'
import {useRuntimePortForward} from './playground-helpers'
import type {components} from '../../../src/web/src/shared/api/generated'

type Original={html:string;htmlHash:string;rawSha256:string;sourceFile:string;sourceDraftId:string;sourceRevision:number;sourceSessionId:string;sourceRunIds:string[];originalPassed:boolean}
type Draft=components['schemas']['ApplicationPageDraftV1']
type Publication={id:string;uiVersionId:string;slug:string;status:string;manifest:{htmlHash:string;contract:Record<string,unknown>;sdk:{contentHash:string}}}
type AdditionalDelivery={scenario:Scenario&{deploymentId:string};originContract:Record<string,unknown>;original:Original;suffix:string}
const input=JSON.parse(process.env.AGENTX_E2E_PLAN9_REVALIDATION!) as {scenario:Scenario&{deploymentId:string};originContract:Record<string,unknown>;earlier:Original;original:Original;other:{scenario:Scenario&{deploymentId:string;slug:string};originContract:Record<string,unknown>;original:Original};additionalDeliveries:AdditionalDelivery[];suffix:string;report:string;sourceRunId:string;definitionExactReplay:boolean}
const metadataKeys=new Set(['applicationId','applicationName','deploymentId','workflowVersionId','bundleId'])
function shape(value:Record<string,unknown>){return Object.fromEntries(Object.entries(value).filter(([key])=>!metadataKeys.has(key)))}

test('Exact original AI HTML passes fixed inspection, formal loop inputs and original-page history without another AI Run',async({page,browser},info)=>{
 test.setTimeout(900_000)
 const result:{passed:boolean;executions:unknown[];history?:{activePublicationId:string;restoredPublicationId:string};[key:string]:unknown}={passed:false,executions:[]}
 const save=()=>writeFileSync(input.report,JSON.stringify(result,null,2))
 await useRuntimePortForward(page)
 const token=trackAccessToken(page,await login(page))
 let authoringRequests=0
 page.on('request',request=>{if(request.method()==='POST'&&/\/(?:application-ui|design-agent)\/sessions\/[^/]+\/runs$/.test(new URL(request.url()).pathname))authoringRequests+=1})
 async function publishOriginal(source:Original,scenario=input.scenario,originContract=input.originContract,suffix=input.suffix){
  expect(createHash('sha256').update(source.html).digest('hex')).toBe(source.rawSha256)
  const path=`/applications/${scenario.applicationId}/ui/drafts`
  // Replay previously generated bytes through the real administrator save path.
  // Do not click Generate or start an authoring Run, and never edit the source.
  const created=await page.request.post(`/api/v1${path}`,{headers:{Authorization:`Bearer ${await token()}`},data:{deploymentId:scenario.deploymentId}})
  expect(created.ok(),await created.text()).toBe(true)
  const initial=await created.json() as Draft
  expect(initial.html).toBe('')
  expect(shape(initial.contract as unknown as Record<string,unknown>)).toEqual(shape(originContract))
  const saved=await page.request.put(`/api/v1${path}/${initial.id}`,{headers:{Authorization:`Bearer ${await token()}`},data:{saveId:crypto.randomUUID(),baseRevision:initial.revision,html:source.html}})
  expect(saved.ok(),await saved.text()).toBe(true)
  const draft=await read<Draft>(page,await token(),`${path}/${initial.id}`)
  expect(draft.html).toBe(source.html);expect(draft.htmlHash).toBe(source.htmlHash)
  await page.goto(`/applications/${scenario.applicationId}`)
  // The latest official draft is selected by the existing application tab.
  // Session binding is permitted; model Run creation remains forbidden.
  const bound=await clickForResponse(page,page.getByRole('tab',{name:'访问界面',exact:true}),response=>response.url().endsWith(`/ui/drafts/${draft.id}/builder-sessions`)&&response.request().method()==='POST')
  expect(bound.ok(),await bound.text()).toBe(true)
  const binding=await bound.json() as {id:string;uiDraftId:string}
  expect(binding.uiDraftId).toBe(draft.id)
  await expect(page.getByTestId('application-page-agent')).toBeVisible()
  await page.getByRole('tab',{name:'检查结果',exact:true}).click()
  const checked=await clickForResponse(page,page.getByRole('button',{name:'重新检查',exact:true}),response=>response.url().endsWith(`/ui/drafts/${draft.id}/checks`)&&response.request().method()==='POST'&&response.request().postDataJSON().mode==='preview')
  expect(checked.ok(),await checked.text()).toBe(true)
  const report=checked.request().postDataJSON()
  expect(report.htmlHash).toBe(source.htmlHash);expect(report.errors).toEqual([]);expect(report.formalRequests).toBe(0)
  await page.getByLabel('访问后缀',{exact:true}).fill(suffix)
  const published=await clickForResponse(page,page.getByTestId('application-publish-page'),response=>response.url().endsWith(`/applications/${scenario.applicationId}/ui/publications`)&&response.request().method()==='POST')
  expect(published.ok(),await published.text()).toBe(true)
  const id=(await published.json()).id as string
  let publication:Publication|undefined
  await expect.poll(async()=>{const list=await read<{publications:Publication[]}>(page,await token(),`/applications/${scenario.applicationId}/ui/publications`);publication=list.publications.find(value=>value.id===id);return publication?.status},{timeout:120_000}).toBe('active')
  expect(publication!.manifest.htmlHash).toBe(source.htmlHash)
  expect(shape(publication!.manifest.contract)).toEqual(shape(originContract))
  expect((await read<Draft>(page,await token(),`${path}/${draft.id}`)).html).toBe(source.html)
  expect(authoringRequests).toBe(0)
  return {draftId:draft.id,sessionId:binding.id,applicationId:scenario.applicationId,publication:publication!,check:report,original:source}
 }
 try{
  const earlier=await publishOriginal(input.earlier)
  result.historySeedPublication=earlier;save()
  result.historySeedExecution=await executeCase(browser,input.scenario,input.suffix,0,info,0);save()
  const current=await publishOriginal(input.original)
  expect(current.publication.id).not.toBe(earlier.publication.id)
  result.revalidatedPublication=current
  result.originalHtmlHash=input.original.htmlHash;result.originalRawSha256=input.original.rawSha256
  result.originalDraftId=input.original.sourceDraftId;result.originalGenerationRevision=input.original.sourceRevision;result.originalSessionId=input.original.sourceSessionId
  result.originalGenerationRunIds=input.original.sourceRunIds;result.originalSourceRun=input.sourceRunId
  save()
  for(let index=0;index<2;index++){result.executions.push(await executeCase(browser,input.scenario,input.suffix,index,info,2));save()}
  result.history=await verifyHistoricalPage(browser,input.scenario,input.suffix,info)
  expect(result.history.restoredPublicationId).toBe(earlier.publication.id)
  // Re-deliver one other original AI page for the complete cross-application
  // authoring boundary regression. No extra business execution or AI Run.
  result.boundaryAlternate=await publishOriginal(input.other.original,input.other.scenario,input.other.originContract,input.other.scenario.slug)
  const deliveries=[]
  for(const delivery of input.additionalDeliveries){deliveries.push(await publishOriginal(delivery.original,delivery.scenario,delivery.originContract,delivery.suffix));result.additionalOriginalDeliveries=deliveries;save()}
  expect(authoringRequests).toBe(0)
  result.passed=true;result.newPageAuthoringRequests=authoringRequests;save()
 }finally{save();await info.attach('original-ai-page-revalidation',{contentType:'application/json',body:JSON.stringify(result)})}
})
