import { readFile } from 'node:fs/promises'
import { expect, type Locator, type Page, test } from '@playwright/test'

async function select(page: Page, field: Locator, option: string) {
  await field.click()
  await page.getByRole('option', { name: option, exact: true }).click()
}

async function expectDialogInViewport(page: Page, dialog: Locator) {
  const bounds = await dialog.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.y).toBeGreaterThanOrEqual(16)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(page.viewportSize()!.height - 16)
}

test('schedule inputs use parameter dropdowns, edit without type loss, and reach a scheduled execution', async ({ page }, testInfo) => {
  const fixture = JSON.parse(await readFile(process.env.AGENTX_SCHEDULE_FIXTURE!, 'utf8')) as { workflowName: string; workflowVersion: number; environment: string }
  const runId = process.env.AGENTX_E2E_RUN_ID!
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码').fill('agentx-e2e-admin-password')
  const loggedIn = page.waitForResponse(response => response.url().endsWith('/api/v1/auth/login') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  const token = (await (await loggedIn).json()).accessToken
  await expect(page).toHaveURL(/\/$/)
  const headers = { Authorization: `Bearer ${token}` }
  const api = async (path: string) => {
    const response = await page.request.get(`/api/v1${path}`, { headers })
    expect(response.ok(), await response.text()).toBeTruthy()
    return response.json()
  }

  await page.getByRole('link', { name: '应用', exact: true }).click()
  await page.getByRole('button', { name: '新建应用', exact: true }).click()
  const create = page.getByRole('dialog', { name: '新建应用', exact: true })
  await select(page, create.getByRole('combobox', { name: '工作流', exact: true }), fixture.workflowName)
  await create.getByLabel('名称', { exact: true }).fill(`Schedule application ${runId}`)
  await create.getByLabel('Slug', { exact: true }).fill(`schedule-${runId}`)
  await create.getByRole('button', { name: '保存', exact: true }).click()
  await expect(create).toBeHidden()
  await expect(page).toHaveURL(/\/applications\/[^/]+$/)
  const applicationId = new URL(page.url()).pathname.split('/').at(-1)!
  expect(await api(`/applications/${applicationId}/deployments`)).toEqual([])
  await page.getByRole('tab', { name: '触发器', exact: true }).click()
  await page.getByRole('button', { name: '新建', exact: true }).click()
  let form = page.getByRole('dialog', { name: '定时触发', exact: true })
  await form.getByLabel('名称', { exact: true }).fill('Typed schedule')
  await form.getByLabel('Cron', { exact: true }).fill('*/10 * * * * *')
  await expect(form.getByRole('textbox', { name: /JSON/ })).toHaveCount(0)
  await expect(form.getByRole('combobox', { name: '工作流输入', exact: true })).toHaveCount(4)
  await expect(form.getByRole('spinbutton', { name: '数量', exact: true })).toHaveValue('0')
  await expect(form.getByRole('combobox', { name: '启用选项', exact: true })).toHaveText('否')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form.getByLabel('消息', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(form.getByLabel('消息', { exact: true })).toBeFocused()
  expect(await api(`/applications/${applicationId}/schedules`)).toEqual([])
  await form.getByLabel('消息', { exact: true }).fill('First scheduled message')
  await select(page, form.getByRole('combobox', { name: '模式', exact: true }), 'fast')
  await select(page, form.getByRole('combobox', { name: '启用选项', exact: true }), '是')
  await select(page, form.getByRole('combobox', { name: '启用选项', exact: true }), '否')
  await expectDialogInViewport(page, form)
  await page.screenshot({ path: testInfo.outputPath('schedule-inputs-zh-light.png'), fullPage: true })
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form).toBeHidden()
  let schedules = await api(`/applications/${applicationId}/schedules`)
  expect(schedules).toHaveLength(1)
  expect(schedules[0].input).toEqual({ message: 'First scheduled message', count: 0, enabled: false, mode: 'fast' })

  const row = page.getByRole('group', { name: 'Typed schedule', exact: true })
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  form = page.getByRole('dialog', { name: '编辑定时触发', exact: true })
  await expect(form.getByLabel('消息', { exact: true })).toHaveValue('First scheduled message')
  await expect(form.getByRole('spinbutton', { name: '数量', exact: true })).toHaveValue('0')
  await expect(form.getByRole('combobox', { name: '启用选项', exact: true })).toHaveText('否')
  await select(page, form.getByRole('combobox', { name: '添加输入参数', exact: true }), 'options')
  await form.getByLabel('地区', { exact: true }).fill('上海')
  await select(page, form.getByRole('group', { name: '参数 options', exact: true }).getByRole('combobox', { name: '工作流输入', exact: true }), 'tags')
  await expect(form.getByLabel('地区', { exact: true })).toHaveCount(0)
  await select(page, form.getByRole('group', { name: '参数 tags', exact: true }).getByRole('combobox', { name: '工作流输入', exact: true }), 'options')
  await form.getByLabel('地区', { exact: true }).fill('上海')
  await select(page, form.getByRole('combobox', { name: '添加输入参数', exact: true }), 'tags')
  await form.getByRole('button', { name: '添加数组项', exact: true }).click()
  await form.getByLabel('tags.0', { exact: true }).fill('daily')
  await form.getByRole('button', { name: '添加数组项', exact: true }).click()
  await form.getByRole('button', { name: '删除参数 tags.1', exact: true }).click()
  await form.getByRole('group', { name: '参数 options', exact: true }).getByRole('combobox', { name: '工作流输入', exact: true }).click()
  await expect(page.getByRole('option', { name: '消息 (message) *', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(form).toBeVisible()
  await expectDialogInViewport(page, form)
  await form.getByLabel('消息', { exact: true }).fill('Scheduled through parameter form')
  await form.getByRole('button', { name: '取消', exact: true }).click()
  schedules = await api(`/applications/${applicationId}/schedules`)
  expect(schedules[0].input.message).toBe('First scheduled message')
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  form = page.getByRole('dialog', { name: '编辑定时触发', exact: true })
  await select(page, form.getByRole('combobox', { name: '添加输入参数', exact: true }), 'options')
  await form.getByLabel('地区', { exact: true }).fill('上海')
  await select(page, form.getByRole('combobox', { name: '添加输入参数', exact: true }), 'tags')
  await form.getByRole('button', { name: '添加数组项', exact: true }).click()
  await form.getByLabel('tags.0', { exact: true }).fill('daily')
  await form.getByLabel('消息', { exact: true }).fill('Scheduled through parameter form')
  await form.getByRole('button', { name: '保存', exact: true }).click()
  await expect(form).toBeHidden()
  const expected = { message: 'Scheduled through parameter form', count: 0, enabled: false, mode: 'fast', options: { region: '上海' }, tags: ['daily'] }
  schedules = await api(`/applications/${applicationId}/schedules`)
  expect(schedules[0].input).toEqual(expected)

  await page.getByRole('button', { name: '语言', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'English', exact: true }).click()
  await page.getByRole('button', { name: 'Theme', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Dark', exact: true }).click()
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  const englishForm = page.getByRole('dialog', { name: 'Edit schedule', exact: true })
  await expect(englishForm.getByText('Input parameters', { exact: true })).toBeVisible()
  await expect(englishForm.getByRole('combobox', { name: '启用选项', exact: true })).toHaveText('No')
  await expect(englishForm.getByLabel('地区', { exact: true })).toHaveValue('上海')
  await page.screenshot({ path: testInfo.outputPath('schedule-inputs-en-dark.png'), fullPage: true })
  await englishForm.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Language', exact: true }).click()
  await page.getByRole('menuitemradio', { name: '简体中文', exact: true }).click()
  await page.getByRole('tab', { name: '应用部署', exact: true }).click()
  await page.getByRole('button', { name: '创建部署', exact: true }).click()
  const deploy = page.getByRole('dialog', { name: '部署', exact: true })
  await select(page, deploy.getByRole('combobox', { name: '工作流版本', exact: true }), `v${fixture.workflowVersion}`)
  await select(page, deploy.getByRole('combobox', { name: '环境', exact: true }), fixture.environment)
  await deploy.getByRole('button', { name: '保存', exact: true }).click()
  await expect(deploy).toBeHidden()
  await expect.poll(async () => (await api(`/applications/${applicationId}/deployments`))[0]?.status, { timeout: 180_000 }).toBe('active')
  let executionId: string | undefined
  await expect.poll(async () => {
    const result = await api(`/executions?applicationIds=${applicationId}&triggerTypes=schedule&limit=50`)
    const completed = result.items.find((item: { status: string }) => item.status === 'succeeded')
    executionId = completed?.id
    return Boolean(completed)
  }, { timeout: 120_000 }).toBe(true)
  const execution = await api(`/executions/${executionId}`)
  expect(execution.input).toEqual(expected)
  expect(execution.output).toEqual({ answer: expected.message })
  await testInfo.attach('scheduled-execution', { body: JSON.stringify({ applicationId, executionId, input: execution.input, output: execution.output }), contentType: 'application/json' })
})
