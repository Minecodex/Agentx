import { expect, test } from '@playwright/test'

const agentExecution = process.env.AGENTX_E2E_TRACE_AGENT_EXECUTION
const reportExecution = process.env.AGENTX_E2E_TRACE_REPORT_EXECUTION

test.beforeEach(async ({ page }) => {
  test.skip(!agentExecution || !reportExecution, 'Requires isolated pytest trace presentation fixtures')
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码').fill('agentx-e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
})

for (const locale of ['zh-CN', 'en-US'] as const) {
  test(`Trace node Markdown, vertical accordions and JSON in ${locale}`, async ({ page }, testInfo) => {
    await page.evaluate((language) => {
      localStorage.setItem('agentx.locale', language)
      localStorage.setItem('agentx.theme', language === 'zh-CN' ? 'light' : 'dark')
    }, locale)
    await page.goto(`/executions/${reportExecution}`)
    await expect(page.locator('html')).toHaveAttribute('data-theme', locale === 'zh-CN' ? 'light' : 'dark')
    const card = page.getByTestId('trace-node-card').filter({ hasText: '报告整理' })
    await expect(card).toBeVisible()
    const cardToggle = card.getByRole('button').first()
    if (await cardToggle.getAttribute('aria-expanded') !== 'true') await cardToggle.click()
    const input = card.getByRole('button', { name: /输入与解析参数|Input and resolved parameters/, exact: true })
    const output = card.getByRole('button', { name: /语义输出|Semantic output/, exact: true })
    await expect(input).toHaveAttribute('aria-expanded', 'false')
    await expect(output).toHaveAttribute('aria-expanded', 'false')
    await expect(card.getByRole('heading', { name: '订单核算报告' })).toHaveCount(0)
    const inputBox = await input.boundingBox()
    const outputBox = await output.boundingBox()
    expect(outputBox!.y).toBeGreaterThan(inputBox!.y + inputBox!.height - 1)
    expect(outputBox!.x).toBe(inputBox!.x)
    expect(outputBox!.width).toBe(inputBox!.width)

    await input.click()
    await expect(card.getByRole('heading', { name: '订单核算报告' })).toHaveCount(1)
    const parameters = card.getByText(/^(解析参数|Resolved parameters)$/)
    await parameters.click()
    await expect(card.getByText('common', { exact: true })).toBeVisible()
    await parameters.click()
    await expect(card.getByText('common', { exact: true })).toBeHidden()
    await output.click()
    await expect(card.getByRole('heading', { name: '订单核算报告' })).toHaveCount(2)
    await expect(card.getByRole('table')).toHaveCount(2)
    await expect(card.getByRole('cell', { name: '558.00' })).toHaveCount(2)
    await input.click()
    await expect(card.getByRole('heading', { name: '订单核算报告' })).toHaveCount(1)
    const json = card.getByTestId('trace-json-value').first()
    await json.getByRole('button', { name: /order/ }).click()
    await expect(json.getByText('558', { exact: true })).toBeVisible()
    await expect(json.getByText('true', { exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath(`trace-content-${locale}.png`), fullPage: true })
    await json.getByRole('button').first().click()
    await expect(json.getByText('558', { exact: true })).toHaveCount(0)
    await output.click()
    await expect(card.getByRole('heading', { name: '订单核算报告' })).toHaveCount(0)
  })
}

test('Advanced waterfall keeps runtime calls inside the Agent hierarchy when collapsed and filtered', async ({ page }, testInfo) => {
  await page.goto(`/executions/${agentExecution}`)
  await page.getByRole('tab', { name: '高级瀑布', exact: true }).click()
  const tree = page.getByRole('treegrid', { name: 'Trace 层级瀑布' })
  const call = tree.getByRole('row').filter({ hasText: 'Model call' }).first()
  await expect(call).toBeVisible()
  expect(Number(await call.getAttribute('aria-level'))).toBeGreaterThan(4)
  const node = tree.getByRole('row').filter({ has: page.getByText('节点', { exact: true }) }).first()
  await expect(node).toBeVisible()
  await node.getByRole('button', { name: '折叠', exact: true }).click()
  await expect(tree.getByRole('row').filter({ hasText: 'Model call' })).toHaveCount(0)
  await node.getByRole('button', { name: '展开', exact: true }).click()
  await expect(call).toBeVisible()
  await page.getByRole('textbox', { name: '搜索 Span、ID 或错误码' }).fill('Model call')
  await expect(node).toBeVisible()
  await expect(call).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('trace-waterfall.png'), fullPage: true })
})
