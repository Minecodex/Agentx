import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { useRuntimePortForward } from './playground-helpers'

test('configure a single Hook below exits, then run preset ASR rounds in Playground', async ({ page }, testInfo) => {
  const fixture = JSON.parse(await readFile(process.env.AGENTX_INTERACTION_FIXTURE!, 'utf8')) as { applicationId: string; workflowId: string; versionId: string }
  await useRuntimePortForward(page)
  await page.goto('/login')
  await page.getByLabel('用户名').fill('admin')
  await page.getByLabel('密码').fill('agentx-e2e-admin-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto(`/workflows/${fixture.workflowId}/versions/${fixture.versionId}/editor`)
  await expect(page.locator('.react-flow__node[data-id="ask"]')).toBeAttached()
  await page.getByRole('button', { name: /^(适应画布|Fit view)$/ }).click()
  await page.locator('.react-flow__node[data-id="ask"]').click()
  const panel = page.getByTestId('await-input-panel')
  await expect(panel).toBeVisible()
  const hook = panel.getByTestId('await-input-hook')
  expect(await panel.getByTestId('await-input-exits').evaluate((element) => Boolean(element.compareDocumentPosition(document.querySelector('[data-testid="await-input-hook"]')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBeTruthy()
  await expect(hook.locator('[data-field-path="parameters.hookUrl"]')).toHaveCount(1)
  await expect(panel.locator('[data-field-path="parameters.candidateUserId"]')).toHaveCount(0)
  const hookEditor = hook.getByTestId('parameter-hookUrl').getByRole('textbox')
  const configuredHook = 'https://customer.example/workflow-hook'
  await hookEditor.fill(configuredHook)
  const save = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().includes(`/workflows/${fixture.workflowId}/drafts/`))
  await page.locator('header').getByRole('button', { name: '保存', exact: true }).click()
  expect((await save).ok()).toBeTruthy()
  await page.reload()
  await expect(page.locator('.react-flow__node[data-id="ask"]')).toBeAttached()
  await page.getByRole('button', { name: /^(适应画布|Fit view)$/ }).click()
  await page.locator('.react-flow__node[data-id="ask"]').click()
  if (await hookEditor.getAttribute('contenteditable') === 'true') await expect(hookEditor).toHaveText(configuredHook)
  else await expect(hookEditor).toHaveValue(configuredHook)
  await panel.getByTestId('await-input-exits').scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('await-input-configuration-zh-light.png'), fullPage: true })
  await hook.getByText('Hook 通知示例', { exact: true }).click()
  await expect(hook).toContainText('workflow.input_required')
  await hook.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('await-input-hook-zh-light.png'), fullPage: true })
  await page.getByTestId('node-details-view').getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.react-flow__node[data-id="progress"]').click()
  await expect(page.getByTestId('reply-message-panel')).toBeVisible()
  await expect(page.getByTestId('reply-message-panel').locator('[data-field-path="parameters.hookUrl"]')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('reply-message-panel-zh-light.png'), fullPage: true })

  await page.goto(`/playground?applicationId=${fixture.applicationId}&mode=parameters`)
  const replies = page.getByTestId('wait-inputs-editor').locator('[data-node-path="/ask"]')
  await expect(replies).toBeVisible()
  await replies.getByRole('button', { name: '添加回复', exact: true }).click()
  await replies.getByRole('textbox').fill('我再考虑一下')
  await replies.getByRole('button', { name: '添加回复', exact: true }).click()
  await replies.getByRole('textbox').nth(1).fill('确认')
  await page.getByRole('textbox', { name: /^message$/i }).fill('从测试台发起语音确认流程')
  await page.getByRole('button', { name: '运行测试', exact: true }).click()
  await expect(page.getByTestId('workflow-interactions')).toContainText('正在执行，请回复确认', { timeout: 60000 })
  await expect(page.getByTestId('workflow-interactions')).toContainText('收到您的内容，请回复确认继续', { timeout: 60000 })
  await expect(page.locator('pre').filter({ hasText: '"answer": "确认"' })).toBeVisible({ timeout: 60000 })
  await page.screenshot({ path: testInfo.outputPath('playground-preset-replies-zh-light.png'), fullPage: true })
})
